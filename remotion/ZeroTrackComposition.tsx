import React from "react";
import { Audio, Series, AbsoluteFill, staticFile } from "remotion";
import { MasterVideoState } from "@/types/schema";
import { BackgroundLayer } from "./components/BackgroundLayer";
import { MascotLayer } from "./components/MascotLayer";
import { CaptionsLayer } from "./components/CaptionsLayer";
import { OverlaysLayer } from "./components/OverlaysLayer";

interface ZeroTrackCompositionProps {
  state: MasterVideoState;
}

const resolveAudioSrc = (src?: string) => {
  if (!src) return undefined;
  if (src.startsWith("/")) return staticFile(src);
  return src;
};

export const ZeroTrackComposition: React.FC<ZeroTrackCompositionProps> = ({ state }) => {
  if (!state || !state.scenes || state.scenes.length === 0) {
    return (
      <AbsoluteFill
        style={{
          backgroundColor: "#090d16",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          color: "#94a3b8",
          fontSize: 24,
          fontFamily: "Inter, sans-serif",
        }}
      >
        No scenes in project state
      </AbsoluteFill>
    );
  }

  const bgMusic = resolveAudioSrc(state.audio.backgroundMusicUrl);
  const voiceTrack = resolveAudioSrc(state.audio.voiceTrackUrl);

  return (
    <AbsoluteFill style={{ backgroundColor: "#090d16", overflow: "hidden" }}>
      {/* Background Music with Auto-Ducking */}
      {bgMusic && (
        <Audio
          src={bgMusic}
          volume={state.audio.musicVolume ?? 0.2}
          loop
        />
      )}

      {/* Primary Voice Track generated by Kokoro & aligned with Whisper */}
      {voiceTrack && (
        <Audio src={voiceTrack} volume={1.0} />
      )}

      {/* Sequential Scenes strictly governed by Audio Timestamps */}
      <Series>
        {state.scenes.map((scene) => (
          <Series.Sequence
            key={scene.id}
            durationInFrames={Math.max(1, scene.durationInFrames)}
          >
            <AbsoluteFill>
              {/* Layer 1: Background (FLUX Klein / Stock / Color with Ken Burns) */}
              <BackgroundLayer
                background={scene.background}
                sceneDurationInFrames={scene.durationInFrames}
              />

              {/* Layer 2: Graphic Overlays */}
              <OverlaysLayer
                overlays={scene.overlays}
                mascot={scene.mascot}
              />

              {/* Layer 3: Mascot (Comic-ink Lightbulb Character) */}
              <MascotLayer mascot={scene.mascot} />

              {/* Layer 4: Semantic Word-Level Captions */}
              <CaptionsLayer scene={scene} />
            </AbsoluteFill>
          </Series.Sequence>
        ))}
      </Series>
    </AbsoluteFill>
  );
};
